create table public.xray_revenue_page_views (
  id uuid primary key default gen_random_uuid(),
  path text not null default '/',
  referrer text,
  metadata jsonb not null default '{}'::jsonb,
  viewed_at timestamptz not null default now()
);

create table public.xray_revenue_sessions (
  id uuid primary key default gen_random_uuid(),
  write_token_hash text not null,
  status text not null default 'started' check (status in ('started','in_progress','completed','abandoned')),
  current_step smallint not null default 0 check (current_step between 0 and 5),
  answers jsonb not null default '{}'::jsonb,
  email text,
  gym_name text,
  city text,
  state text,
  started_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz
);

create table public.xray_revenue_events (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.xray_revenue_sessions(id) on delete cascade,
  event_name text not null,
  step smallint,
  payload jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now()
);

create table public.xray_revenue_reports (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null unique references public.xray_revenue_sessions(id) on delete cascade,
  public_slug text not null unique,
  report_data jsonb not null,
  unlocked boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.xray_revenue_market_research (
  id uuid primary key default gen_random_uuid(),
  session_id uuid not null unique references public.xray_revenue_sessions(id) on delete cascade,
  status text not null default 'queued' check (status in ('queued','processing','completed','failed')),
  location_query text not null,
  request_fingerprint text not null,
  result jsonb not null default '{}'::jsonb,
  sources jsonb not null default '[]'::jsonb,
  model text,
  openai_response_id text,
  error_message text,
  attempt_count integer not null default 0,
  started_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

